# сортируем по длине убыв. — чтобы «Нижний Новгород» матчился раньше «Новгород»
CITIES.sort(key=len, reverse=True)
LOWER = [(c, c.lower()) for c in CITIES]
GEO = re.compile(r"([А-ЯЁ][А-Яа-яёЁ-]+(?:\s[А-ЯЁ][а-яё]+)?)\s+г[.,]")  # «Москва г,»


def find_city(text_val: str):
    if not text_val:
        return None
    low = text_val.lower()
    for canon, lc in LOWER:                       # словарь (whole-word)
        if re.search(r"(?<![а-яё])" + re.escape(lc) + r"(?![а-яё])", low):
            return "Королёв" if canon == "Королев" else ("Орёл" if canon == "Орел" else canon)
    m = GEO.search(text_val)                      # «<Город> г,»
    if m:
        return m.group(1).strip()
    return None


def main():
    eng = get_engine()
    with eng.begin() as conn:
        rows = conn.execute(text(
            "SELECT tt_id, COALESCE(NULLIF(name,''), client_tt_code) FROM core.dim_tt "
            "WHERE city IS NULL OR city=''")).fetchall()
        upd = 0
        for tt_id, nm in rows:
            city = find_city(nm or "")
            if city:
                conn.execute(text("UPDATE core.dim_tt SET city=:c WHERE tt_id=:t"),
                             {"c": city, "t": tt_id})
                upd += 1
        print(f"проверено точек без города: {len(rows)}, проставлен город: {upd}")


if __name__ == "__main__":
    main()
