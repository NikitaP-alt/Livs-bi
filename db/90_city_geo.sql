CREATE OR REPLACE VIEW marts.v_city_sales AS
WITH norm AS (
  SELECT
    trim(split_part(
      regexp_replace(lower(city), '(^|\s)(г\.?|город|гор\.?)(\s|$)', ' ', 'g'),
      ',', 1)) AS city_n,
    qty
  FROM marts.v_sellout
  WHERE city IS NOT NULL AND city <> ''
)
SELECT g.city AS "Город", g.lat, g.lon, SUM(n.qty)::int AS "Продажи, шт"
FROM norm n
JOIN core.dim_city_geo g ON g.city = n.city_n
GROUP BY g.city, g.lat, g.lon;
